# DCT Restoration Dataset (your existing class, unchanged logic)
# ---------------------------
class DCTRestorationDataset(Dataset):
    def __init__(self, base_dataset, image_size=256, fixed_quality=10):
        self.base_dataset = base_dataset
        self.image_size = image_size
        self.q_scale = self._get_q_scale(fixed_quality)
        '''
        self.transform = T.Compose([
            T.Resize((image_size, image_size)),
            T.ToTensor(),
        ])
        '''
        # --- NEW AUGMENTATION TRANSFORMS ---
        self.transform = T.Compose([
            T.Resize((image_size, image_size)),
            T.RandomHorizontalFlip(p=0.5),  # 50% chance to flip Left/Right
            T.RandomVerticalFlip(p=0.5),    # 50% chance to flip Up/Down
            T.ToTensor(),
        ])

    def __len__(self):
        return len(self.base_dataset)

    def _get_q_scale(self, quality):
        return float(quality)

    def rgb_to_ycbcr(self, img_tensor):
        r, g, b = img_tensor[0], img_tensor[1], img_tensor[2]
        y = 0.299 * r + 0.587 * g + 0.114 * b
        cb = -0.168736 * r - 0.331264 * g + 0.5 * b + 0.5
        cr = 0.5 * r - 0.418688 * g - 0.081312 * b + 0.5
        return torch.stack([y, cb, cr], dim=0)

    def image_to_patches(self, img_channel):
        patches = img_channel.unfold(0, 8, 8).unfold(1, 8, 8)
        patches = patches.contiguous().view(-1, 8, 8)
        return patches

    def dct_2d_batch(self, patches):
        return torch.matmul(DCT_MAT, torch.matmul(patches, DCT_MAT_T))

    def __getitem__(self, idx):
        img_pil, _ = self.base_dataset[idx]
        img_tensor = self.transform(img_pil)  # (3, H, W)

        # RGB -> YCbCr and Y channel in JPEG centered format
        ycbcr = self.rgb_to_ycbcr(img_tensor)
        y_channel = ycbcr[0] * 255.0 - 128.0

        # Patching, DCT, Quantization
        blocks_flat = self.image_to_patches(y_channel)
        dct_coeffs = self.dct_2d_batch(blocks_flat)

        q_table = JPEG_LUM_QUANT * self.q_scale
        q_table = torch.clamp(q_table, min=1.0)

        dct_quantized = torch.round(dct_coeffs / q_table)

        network_input_raw = dct_quantized * q_table
        true_error = dct_coeffs - network_input_raw
        target_error = true_error / q_table

        blocks_h = self.image_size // 8
        blocks_w = self.image_size // 8

        input_stack = dct_quantized.view(blocks_h, blocks_w, 64)
        target_stack = target_error.view(blocks_h, blocks_w, 64)

        input_stack = input_stack.permute(2, 0, 1)
        target_stack = target_stack.permute(2, 0, 1)

        return {
            "pixel_values": input_stack,
            "labels": target_stack,
            "q_scale": self.q_scale
        }

# ---------------------------
# Small helper to build a DataLoader easily
# ---------------------------
def build_dct_loader(dataset_path, image_size=256, q=10, batch_size=1, shuffle=True, num_workers=4):
    base = DIV2KDataset(dataset_path)
    dct = DCTRestorationDataset(base, image_size=image_size, fixed_quality=q)
    return DataLoader(dct, batch_size=batch_size, shuffle=shuffle, num_workers=num_workers, pin_memory=True)

