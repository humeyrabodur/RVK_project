import os
import math
import torch
from torch.utils.data import Dataset, DataLoader
import torchvision.transforms as T
from PIL import Image

# --- 1. JPEG CONSTANTS for quantization ---
JPEG_LUM_QUANT = torch.tensor([
    [16, 11, 10, 16, 24, 40, 51, 61],
    [12, 12, 14, 19, 26, 58, 60, 55],
    [14, 13, 16, 24, 40, 57, 69, 56],
    [14, 17, 22, 29, 51, 87, 80, 62],
    [18, 22, 37, 56, 68, 109, 103, 77],
    [24, 35, 55, 64, 81, 104, 113, 92],
    [49, 64, 78, 87, 103, 121, 120, 101],
    [72, 92, 95, 98, 112, 100, 103, 99]
], dtype=torch.float32)

def get_dct_matrix():
    N = 8
    mat = torch.zeros((N, N))
    for u in range(N):
        for x in range(N):
            norm = math.sqrt(1/N) if u == 0 else math.sqrt(2/N)
            mat[u, x] = norm * math.cos(((2*x + 1) * u * math.pi) / (2*N))
    return mat

DCT_MAT = get_dct_matrix()
DCT_MAT_T = DCT_MAT.t()

# ---------------------------
# Base dataset: loads images from a folder (no hard-coded paths)
# ---------------------------
class DIV2KDataset(Dataset):
    def __init__(self, root_dir):
        self.root_dir = root_dir
        self.image_files = sorted([
            f for f in os.listdir(root_dir)
            if f.lower().endswith(('.png', '.jpg', '.jpeg'))
        ])
        if len(self.image_files) == 0:
            raise RuntimeError(f"No images found in {root_dir}")

    def __len__(self):
        return len(self.image_files)

    def __getitem__(self, idx):
        img_path = os.path.join(self.root_dir, self.image_files[idx])
        img = Image.open(img_path).convert("RGB")
        return img, 0  # dummy label for compatibility

